import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const read = name => readFile(resolve(root, name), 'utf8');
const pkg = JSON.parse(await read('package.json'));
const version = `// Generated from package.json by scripts/build.mjs.\nexport const VERSION = '${pkg.version}';\n`;
async function output(name, contents, executable = false) {
  const path = resolve(root, name);
  if (check) {
    const current = await readFile(path, 'utf8').catch(() => '');
    if (current !== contents) throw new Error(`${name} is stale; run npm run build.`);
  } else {
    await mkdir(dirname(path), {recursive: true});
    await writeFile(path, contents, {mode: executable ? 0o755 : 0o644});
  }
}
await output('src/version.mjs', version);
const shared = await read('src/file-transfer.mjs');
const names = [...shared.matchAll(/^export (?:const|function|class) (\w+)/gm)].map(match => match[1]);
const imports = new Set(["import { pathToFileURL } from 'node:url';"]);
const parts = [`// BEGIN GENERATED SHARED FILE V2\n// Source: src/file-transfer.mjs in the pinned VRCH MCP release.\nconst sharedFileV2 = (() => {\n${shared.replace(/^export /gm, '')}\nreturn {${names.join(', ')}};\n})();\n// END GENERATED SHARED FILE V2`];
for (const name of ['client', 'version', 'tool-metadata', 'mcp', 'cli']) {
  let source = name === 'version' ? version : await read(`src/${name}.mjs`);
  source = source.replace(/^import .*;\n/gm, line => {
    if (line.includes("from 'node:")) imports.add(line.trim());
    return '';
  }).replace(/^export /gm, '');
  parts.push(source.trim());
}
const body = `#!/usr/bin/env node\n// Generated by scripts/build.mjs; edit src/, not this bundle.\n${[...imports].join('\n')}\n\n${parts.join('\n\n')}\n\nexport { createAIClient, createTerminalMCP, validateHTTPOrigin };\n`;
for (const [name, options] of [
  ['vrch-mcp.mjs', ''],
  ['vrch_terminal_ai_client.mjs', "{ defaultMode: '', defaultCatalog: 'dynamic' }"]
]) {
  await output(`dist/${name}`, `${body}\nif (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) runCLI(${options});\n`, true);
}
console.log(check ? 'Generated bundles match source.' : 'Built both standalone bundles.');
const { createTerminalMCP } = await import('../src/mcp.mjs');
const replies = [];
const bridge = createTerminalMCP({send: reply => replies.push(reply), toolCatalog:'stable'});
await bridge.receive({jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2025-11-25'}});
await bridge.receive({jsonrpc:'2.0',id:2,method:'tools/list'});
bridge.close();
await output('docs/tools.json', JSON.stringify({version:pkg.version,tools:replies[1].result.tools},null,2)+'\n');
